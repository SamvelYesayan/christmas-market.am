// Ports the website's procedural product art (client/src/art/Art.jsx, SVG + JSX) to react-native-svg.
// Usage (from mobile/): node scripts/port-art.mjs   → writes src/components/art/drawings.tsx
// Only the drawing code (helpers + DRAW table) is converted; the RN <Art> component lives in src/components/Art.tsx.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const src = fs.readFileSync(path.resolve(here, '../../client/src/art/Art.jsx'), 'utf8');
const start = src.indexOf('const GOLD');
const end = src.indexOf('export default function Art');
let code = src.slice(start, end);

const TAGS = { g: 'G', path: 'Path', rect: 'Rect', circle: 'Circle', ellipse: 'Ellipse', polygon: 'Polygon', line: 'Line', text: 'SvgText', defs: 'Defs', radialGradient: 'RadialGradient', linearGradient: 'LinearGradient', stop: 'Stop' };
for (const [from, to] of Object.entries(TAGS)) {
  code = code.replace(new RegExp('<' + from + '(?=[\\s>/])', 'g'), `<${to}`).replace(new RegExp(`</${from}>`, 'g'), `</${to}>`);
}
// CSS animation hooks do not exist in react-native-svg.
code = code.replace(/\s+className=(\{`[^`]*`\}|"[^"]*")/g, '');
code = code.replace(/\s+style=\{\{ animationDelay: `[^`]*` \}\}/g, '');
// Fonts loaded by the app (expo-google-fonts names); CSS fallback lists are not supported in native SVG.
code = code.replace(/fontFamily="Fraunces, serif"/g, 'fontFamily="Fraunces_600SemiBold"').replace(/fontFamily="Pinyon Script, cursive"/g, 'fontFamily="Fraunces_500Medium_Italic"');
code = code.replace(/^function Defs/m, 'export function Defs');
code = code.replace(/^const DRAW = /m, 'export const DRAW: Record<string, (id: string, a: any) => any> = ');
code = code.replace(/^export const lighten/m, 'export const lighten').replace(/^const star =/m, 'export const star =');

const header = `// GENERATED by scripts/port-art.mjs from client/src/art/Art.jsx — do not edit by hand; re-run the script.
// Original procedural illustrations of the Christmas Market, drawn with react-native-svg.
// @ts-nocheck — mechanically ported drawing table; the typed boundary is src/components/Art.tsx.
import { Circle, Defs as SvgDefs, Ellipse, G, Line, LinearGradient, Path, Polygon, RadialGradient, Rect, Stop, Text as SvgText } from 'react-native-svg';
const Defs = SvgDefs;
`;
code = code.replace('export function Defs', 'export function ArtDefs');
fs.mkdirSync(path.resolve(here, '../src/components/art'), { recursive: true });
fs.writeFileSync(path.resolve(here, '../src/components/art/drawings.tsx'), header + code);
console.log('wrote src/components/art/drawings.tsx');
